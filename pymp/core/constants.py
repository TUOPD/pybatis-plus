# -*- coding: utf-8 -*-
"""
pymp 框架核心常量定义
作用：集中管理默认参数，避免代码中出现硬编码（Magic Numbers）
"""

# ------------------------------------------------------------------------------
# 1. 数据库主键与字段默认名
# ------------------------------------------------------------------------------
DEFAULT_PRIMARY_KEY: str = "id"               # 默认表主键列名


# ------------------------------------------------------------------------------
# 2. 分页默认配置 (对标 MyBatis-Plus 的 Page 插件默认值)
# ------------------------------------------------------------------------------
DEFAULT_PAGE_NO: int = 1                      # 默认起始页码（从第 1 页开始）
DEFAULT_PAGE_SIZE: int = 10                   # 默认每页查询 10 条数据
MAX_PAGE_SIZE: int = 500                      # 保护性限制：单页最多查 500 条，防止内存爆掉


# ------------------------------------------------------------------------------
# 3. 逻辑删除默认配置 (对标 @TableLogic)
# ------------------------------------------------------------------------------
DEFAULT_LOGIC_DELETE_COLUMN: str = "is_deleted" # 数据库中逻辑删除字段名
DEFAULT_LOGIC_DELETED_VAL: int = 1              # 代表 “已删除” 的值
DEFAULT_LOGIC_NOT_DELETED_VAL: int = 0          # 代表 “未删除 (正常)” 的值


# ------------------------------------------------------------------------------
# 4. SQL 占位符风格 (驱动适配)
# ------------------------------------------------------------------------------
PYMYSQL_PLACEHOLDER: str = "%s"                 # PyMySQL / MySQL Connector 占位符
SQLITE_PLACEHOLDER: str = "?"                   # SQLite 占位符
POSTGRES_PLACEHOLDER: str = "%s"                # psycopg2 占位符 (%s 或 $1)